# Basic Operators +,-,*,/,//,%,**
a = 20
b = 15
x = a / b
print (x)
z = a * b
print (z)
# Floor Division - Whole number with no remainder
print (a // b)
# Modules(Remainder) - The % operator returns the remainder of a division operation.
print (a % b)
# Exponentiation - The ** operator raises a number to the power of another number.
print (a ** b)
# Comparison operators compare two values and return either True or False.
print (a > b) # greater than
print (a < b) # less than
print (a == b) # equal to
print (a != b) # not equal to
print (a >= b) # greater than or equal to
print (a <= b) # less than or equal to